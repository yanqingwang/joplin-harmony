def main():
    apply = '--apply' in sys.argv
    zh = json.load(open(LIB))
    en = json.load(open('packages/lib/locales/en_US.json'))
    filled, added, conflict = 0, 0, []
    for k, v in T.items():
        if k not in en:
            conflict.append(f'NOT-IN-EN: {k[:60]}')
            continue
        if k in zh:
            cur = zh[k][0] if isinstance(zh[k], list) else zh[k]
            if cur == '':
                zh[k] = [v]
                filled += 1
            elif cur != v:
                conflict.append(f'CONFLICT: {k[:60]!r} existing={cur[:30]!r}')
        else:
            zh[k] = [v]
            added += 1
    print(f'filled empty: {filled}, added new: {added}, problems: {len(conflict)}')
    for c in conflict[:10]:
        print(' ', c)
    if apply:
        # keep key order: match en_US ordering style (case-insensitive alpha) like build-translation does
        out = dict(sorted(zh.items(), key=lambda kv: kv[0].lower()))
        json.dump(out, open(LIB, 'w'), ensure_ascii=False, indent='\t', separators=(',', ': '))
        # Joplin json uses ": [" on separate lines; rewrite with json-style arrays expanded
        print('APPLIED to', LIB)
    else:
        print('DRY RUN (pass --apply to write)')

main()
